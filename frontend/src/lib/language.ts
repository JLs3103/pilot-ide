export function languageFromPath(path: string) {
    const ext = path.split('.').pop()?.toLowerCase() ?? '';
    const map: Record<string, string> = {
        ts: 'typescript',
        tsx: 'typescript',
        js: 'javascript',
        jsx: 'javascript',
        mjs: 'javascript',
        cjs: 'javascript',
        mts: 'typescript',
        cts: 'typescript',
        json: 'json',
        jsonc: 'json',
        css: 'css',
        scss: 'scss',
        less: 'less',
        html: 'html',
        htm: 'html',
        svg: 'xml',
        xml: 'xml',
        md: 'markdown',
        mdx: 'markdown',
        go: 'go',
        mod: 'go',
        py: 'python',
        pyw: 'python',
        pyi: 'python',
        rs: 'rust',
        sh: 'shell',
        bash: 'shell',
        zsh: 'shell',
        fish: 'shell',
        ps1: 'powershell',
        psm1: 'powershell',
        bat: 'bat',
        cmd: 'bat',
        yml: 'yaml',
        yaml: 'yaml',
        toml: 'ini',
        ini: 'ini',
        conf: 'ini',
        env: 'ini',
        sql: 'sql',
        c: 'c',
        h: 'c',
        cpp: 'cpp',
        cc: 'cpp',
        cxx: 'cpp',
        hpp: 'cpp',
        hh: 'cpp',
        cs: 'csharp',
        java: 'java',
        kt: 'kotlin',
        kts: 'kotlin',
        swift: 'swift',
        php: 'php',
        rb: 'ruby',
        lua: 'lua',
        pl: 'perl',
        pm: 'perl',
        r: 'r',
        dart: 'dart',
        dockerfile: 'dockerfile',
        graphql: 'graphql',
        gql: 'graphql',
        txt: 'plaintext',
        log: 'plaintext',
    };

    const name = path.split(/[\\/]/).pop()?.toLowerCase() ?? '';
    if (name === 'dockerfile' || name === 'dockerfile.dev' || name === 'dockerfile.prod') return 'dockerfile';
    if (name === 'makefile' || name === 'gnumakefile') return 'makefile';
    if (name === '.gitignore' || name === '.dockerignore' || name === '.eslintignore') return 'ignore';
    if (name === '.env' || name === '.env.local' || name === '.env.development') return 'ini';

    return map[ext] ?? 'plaintext';
}
